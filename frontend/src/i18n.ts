/** Simulated habitat clock: morning of mission day 112, starting at 07:02 when the app loads. */
const T0 = Date.now()
export function habitatTime(now = Date.now()) {
  const mins = 7 * 60 + 2 + Math.floor((now - T0) / 60000)
  return `${String(Math.floor(mins / 60) % 24).padStart(2, '0')}:${String(mins % 60).padStart(2, '0')}`
}
